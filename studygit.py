# GIT STUDY 
# GIT save all versions of your code 


### GIT COMMANDS ###


# Inicia um repositório Git no projeto, usar uma vez por projeto
#   git init


# Mostra arquivos modificados, não rastreados e prontos para commit
#   git status


# Adiciona TODOS os arquivos modificados ao staging (preparar para commit)
#   git add .


# Salva uma versão do projeto no histórico
#   git commit -m "mensagem do commit"


# Conecta o projeto a um repositório remoto no GitHub (apenas uma vez)
#   git remote add origin https://github.com/seu_usuario/seu_repositorio.git


# Envia os commits locais para o GitHub (primeiro push com -u)
#   git push -u origin main


# Envia commits posteriores para o GitHub (não precisa do -u toda vez)
#   git push


# Mostra histórico de commits
#   git log


# Baixa atualizações do GitHub
#   git pull


# Baixa projeto completo do GitHub
#   git clone URL